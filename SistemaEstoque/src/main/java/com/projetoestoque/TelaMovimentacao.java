    private void btnEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntradaActionPerformed

try {
    int id = Integer.parseInt(
        txtIdProduto.getText().trim()
    );
    int quantidade = Integer.parseInt(
        txtQuantidade.getText().trim()
    );
    boolean sucesso = ProdutoDAO.movimentarEstoque(
        id, quantidade, true
    );
    if (sucesso) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Entrada registrada com sucesso!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Verifique o ID e a quantidade."
        );
    }
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Digite números inteiros válidos."
    );
}
    }//GEN-LAST:event_btnEntradaActionPerformed

    private void btnSaidaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaidaActionPerformed

try {
    int id = Integer.parseInt(
        txtIdProduto.getText().trim()
    );
    int quantidade = Integer.parseInt(
        txtQuantidade.getText().trim()
    );
    boolean sucesso = ProdutoDAO.movimentarEstoque(
        id, quantidade, false
    );
    if (sucesso) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Saída registrada com sucesso!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Produto não encontrado ou estoque insuficiente."
        );
    }
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Digite números inteiros válidos."
    );
}
    }//GEN-LAST:event_btnSaidaActionPerformed


    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed

javax.swing.table.DefaultTableModel modelo =
    new javax.swing.table.DefaultTableModel(
        new Object[]{"ID", "Produto", "Tipo",
                     "Quantidade", "Data"}, 0
    ) {
        @Override
        public boolean isCellEditable(int linha, int coluna) {
            return false;
        }
    };
String sql = """
    SELECT
        m.id_movimentacao,
        p.nome,
        m.tipo,
        m.quantidade,
        m.data_movimentacao
    FROM movimentacao m
    INNER JOIN produtos p
        ON m.id_produto = p.id
    ORDER BY m.id_movimentacao DESC
    """;
try (java.sql.Connection conn = Conexao.conectar();
     java.sql.PreparedStatement stmt =
         conn.prepareStatement(sql);
     java.sql.ResultSet rs = stmt.executeQuery()) {
    while (rs.next()) {
        modelo.addRow(new Object[]{
            rs.getInt("id_movimentacao"),
            rs.getString("nome"),
            rs.getString("tipo"),
            rs.getInt("quantidade"),
            rs.getString("data_movimentacao")
        });
    }
    tabelaHistorico.setModel(modelo);
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao consultar histórico: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnAtualizarActionPerformed

